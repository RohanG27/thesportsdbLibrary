class AsyncV1Lists:
    """Lists."""

    def __init__(self, r: AsyncRequester) -> None:
        self._r = r

    async def sports(self) -> list[Sport]:
        """``all_sports.php``. Free keys: 2."""
        return await self._r.v1("all_sports.php", "sports", STATIC, Sport._from)

    async def countries(self) -> list[Country]:
        """``all_countries.php``: names and flags. Free keys: 50."""
        return await self._r.v1("all_countries.php", "countries", STATIC, Country._from)

    async def leagues(self) -> list[League]:
        """``all_leagues.php``: id, name, sport (alternate names with a premium key only). Free keys: 5."""
        return await self._r.v1("all_leagues.php", "leagues", STATIC, League._from)

    async def leagues_in_country(self, country: str, sport: str | None = None) -> list[League]:
        """``search_all_leagues.php?c=&s=``: full league records. Note the record key really is ``countries``."""
        return await self._r.v1("search_all_leagues.php", "countries", SLOW, League._from, c=country, s=sport)

    async def seasons(
        self, league_id: int, badges: bool = False, posters: bool = False, descriptions: bool = False
    ) -> list[Season]:
        """``search_all_seasons.php?id=``: season names, plus one of badges, posters or descriptions."""
        if sum((badges, posters, descriptions)) > 1:
            raise ValueError("Ask for one of badges, posters or descriptions per request")
        return await self._r.v1(
            "search_all_seasons.php", "seasons", SLOW, Season._from, id=league_id,
            badge=1 if badges else None, poster=1 if posters else None, description=1 if descriptions else None,
        )

    async def teams_in_league(self, league_name: str) -> list[Team]:
        """``search_all_teams.php?l=``: a league's teams, by league **name**. Free keys: 10.

        Not ``lookup_all_teams.php?id=``, which returns another league's teams.
        """
        return await self._r.v1("search_all_teams.php", "teams", SLOW, Team._from, l=league_name)

    async def teams_in_country(self, sport: str, country: str) -> list[Team]:
        """``search_all_teams.php?s=&c=``. Free keys: 10."""
        return await self._r.v1("search_all_teams.php", "teams", SLOW, Team._from, s=sport, c=country)

    async def players(self, team_id: int) -> list[Player]:
        """``lookup_all_players.php?id=``: a team's squad. Free keys: 10."""
        return await self._r.v1("lookup_all_players.php", "player", SLOW, Player._from, id=team_id)


class AsyncV1Schedule:
    """Schedules and results. Event times are UTC."""

    def __init__(self, r: AsyncRequester) -> None:
        self._r = r

    async def team_next(self, team_id: int) -> list[Event]:
        """``eventsnext.php?id=``. Free keys: 1, home games only."""
        return await self._r.v1("eventsnext.php", "events", MEDIUM, Event._from, id=team_id)

    async def team_last(self, team_id: int) -> list[Event]:
        """``eventslast.php?id=``. Free keys: 1, home games only. (The record key is ``results``.)"""
        return await self._r.v1("eventslast.php", "results", MEDIUM, Event._from, id=team_id)

    async def league_next(self, league_id: int) -> list[Event]:
        """``eventsnextleague.php?id=``. Free keys: 1."""
        return await self._r.v1("eventsnextleague.php", "events", MEDIUM, Event._from, id=league_id)

    async def league_past(self, league_id: int) -> list[Event]:
        """``eventspastleague.php?id=``. Free keys: 1."""
        return await self._r.v1("eventspastleague.php", "events", MEDIUM, Event._from, id=league_id)

    async def day(
        self, date: date, sport: str | None = None, league_id: int | None = None, league_name: str | None = None
    ) -> list[Event]:
        """``eventsday.php?d=``: every event on a UTC day, optionally for one sport or league. Free keys: 3."""
        if league_id is not None and league_name is not None:
            raise ValueError("Pass league_id or league_name, not both")
        league = league_id if league_id is not None else league_name
        return await self._r.v1("eventsday.php", "events", MEDIUM, Event._from, d=date, s=sport, l=league)

    async def season(self, league_id: int, season: str) -> list[Event]:
        """``eventsseason.php?id=&s=``: a whole season (premium). Free keys: 5."""
        return await self._r.v1("eventsseason.php", "events", MEDIUM, Event._from, id=league_id, s=season)

    async def round(self, league_id: int, round: int, season: str) -> list[Event]:
        """``eventsround.php?id=&r=&s=``: one round. **Undocumented and free keys only**: premium keys
        get HTTP 404. ``helpers.round_events`` picks the right route for any key."""
        return await self._r.v1("eventsround.php", "events", MEDIUM, Event._from, id=league_id, r=round, s=season)


class AsyncV1Tv:
    """TV listings. Free keys: 1 per call."""

    def __init__(self, r: AsyncRequester) -> None:
        self._r = r

    async def day(self, date: date, sport: str | None = None, country: str | None = None) -> list[TvListing]:
        """``eventstv.php?d=``: listings for a day, optionally for a sport, or a country **and** sport.
        The API returns an empty body for a country without a sport, so that is rejected here."""
        if country is not None and sport is None:
            raise ValueError("eventstv.php needs a sport when filtering by country")
        return await self._r.v1("eventstv.php", "tvevents", MEDIUM, TvListing._from, d=date, a=country, s=sport)

    async def channel(self, name: str) -> list[TvListing]:
        """``eventstv.php?c=``: upcoming listings on a channel, by name (e.g. ``TSN 1``)."""
        return await self._r.v1("eventstv.php", "tvevents", MEDIUM, TvListing._from, c=name)

    async def channel_id(self, channel_id: int) -> list[TvListing]:
        """``eventstv.php?id=``: by **channel** id (``TvListing.channel_id``), not event id."""
        return await self._r.v1("eventstv.php", "tvevents", MEDIUM, TvListing._from, id=channel_id)


