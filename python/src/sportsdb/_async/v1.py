LIVE, MEDIUM, SLOW, STATIC = Freshness.LIVE, Freshness.MEDIUM, Freshness.SLOW, Freshness.STATIC
T = TypeVar("T")


class AsyncV1Api:
    def __init__(self, r: AsyncRequester) -> None:
        self.search = AsyncV1Search(r)
        self.lookup = AsyncV1Lookup(r)
        self.list = AsyncV1Lists(r)
        self.schedule = AsyncV1Schedule(r)
        self.tv = AsyncV1Tv(r)
        self.video = AsyncV1Video(r)
        self.live = AsyncV1Live(r)


class AsyncV1Search:
    """Search endpoints. Free keys: one result each."""

    def __init__(self, r: AsyncRequester) -> None:
        self._r = r

    async def teams(self, name: str) -> list[Team]:
        """``searchteams.php?t=``: teams by name."""
        return await self._r.v1("searchteams.php", "teams", SLOW, Team._from, t=name)

    async def events(self, name: str, season: str | None = None, date: date | None = None) -> list[Event]:
        """``searchevents.php?e=``: events by name, ``Home vs Away``. Narrow with a season or a date, not both."""
        if season is not None and date is not None:
            raise ValueError("Pass season or date, not both")
        return await self._r.v1("searchevents.php", "event", MEDIUM, Event._from, e=name, s=season, d=date)

    async def events_by_filename(self, filename: str, season: str | None = None) -> list[Event]:
        """``searchfilename.php?e=``: events by ``Event.filename``, e.g. ``English Premier League 2015-04-26 Arsenal vs Chelsea``."""
        return await self._r.v1("searchfilename.php", "event", MEDIUM, Event._from, e=filename, s=season)

    async def players(self, name: str) -> list[Player]:
        """``searchplayers.php?p=``: players by name (summary fields)."""
        return await self._r.v1("searchplayers.php", "player", SLOW, Player._from, p=name)

    async def venues(self, name: str) -> list[Venue]:
        """``searchvenues.php?v=``: venues by name."""
        return await self._r.v1("searchvenues.php", "venues", SLOW, Venue._from, v=name)


