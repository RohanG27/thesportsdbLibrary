class AsyncV2Schedule:
    """``schedule/...``. Event times are UTC."""

    def __init__(self, r: AsyncRequester) -> None:
        self._r = r

    async def league_next(self, league_id: int) -> list[Event]:
        return await self._get("next", "league", league_id)

    async def league_previous(self, league_id: int) -> list[Event]:
        return await self._get("previous", "league", league_id)

    async def team_next(self, team_id: int) -> list[Event]:
        return await self._get("next", "team", team_id)

    async def team_previous(self, team_id: int) -> list[Event]:
        return await self._get("previous", "team", team_id)

    async def venue_next(self, venue_id: int) -> list[Event]:
        return await self._get("next", "venue", venue_id)

    async def venue_previous(self, venue_id: int) -> list[Event]:
        return await self._get("previous", "venue", venue_id)

    async def team_full(self, team_id: int) -> list[Event]:
        """A team's whole schedule, past and future, across all competitions."""
        return await self._get("full", "team", team_id)

    async def league_season(self, league_id: int, season: str) -> list[Event]:
        """A league's whole season in one call. The current season name is ``League.current_season``."""
        return await self._get("league", league_id, season)

    async def _get(self, *path: object) -> list[Event]:
        return await self._r.v2("schedule", MEDIUM, Event._from, "schedule", *path)


class AsyncV2Tv:
    """``filter/tv/...``"""

    def __init__(self, r: AsyncRequester) -> None:
        self._r = r

    async def day(self, date: date) -> list[TvListing]:
        """Every listing worldwide on a day."""
        return await self._get("day", date)

    async def country(self, country: str) -> list[TvListing]:
        """About a week of listings for a country, e.g. ``Canada``."""
        return await self._get("country", country)

    async def sport(self, sport: str) -> list[TvListing]:
        return await self._get("sport", sport)

    async def channel(self, name: str) -> list[TvListing]:
        """By channel name, in the API's spelling (``TSN 1``, not ``TSN1``); partial names match."""
        return await self._get("channel", name)

    async def channel_id(self, channel_id: int) -> list[TvListing]:
        return await self._get("channelid", channel_id)

    async def _get(self, kind: str, value: object) -> list[TvListing]:
        return await self._r.v2("filter", MEDIUM, TvListing._from, "filter", "tv", kind, value)


