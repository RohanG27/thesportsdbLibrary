class AsyncV2Api:
    def __init__(self, r: AsyncRequester) -> None:
        self.search = AsyncV2Search(r)
        self.lookup = AsyncV2Lookup(r)
        self.list = AsyncV2Lists(r)
        self.all = AsyncV2All(r)
        self.schedule = AsyncV2Schedule(r)
        self.tv = AsyncV2Tv(r)
        self.live = AsyncV2Live(r)


class AsyncV2Search:
    """``search/...``: up to about 10 results, summary fields only. Ids arrive as JSON numbers here."""

    def __init__(self, r: AsyncRequester) -> None:
        self._r = r

    async def leagues(self, name: str) -> list[League]:
        return await self._r.v2("search", SLOW, League._from, "search", "league", name)

    async def teams(self, name: str) -> list[Team]:
        return await self._r.v2("search", SLOW, Team._from, "search", "team", name)

    async def players(self, name: str) -> list[Player]:
        return await self._r.v2("search", SLOW, Player._from, "search", "player", name)

    async def events(self, name: str) -> list[Event]:
        """Needs the exact stored event name; a loose ``Arsenal vs Chelsea`` finds nothing."""
        return await self._r.v2("search", MEDIUM, Event._from, "search", "event", name)

    async def venues(self, name: str) -> list[Venue]:
        return await self._r.v2("search", SLOW, Venue._from, "search", "venue", name)


